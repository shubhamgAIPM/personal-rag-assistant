// Generates supabase/seed/demo_seed.sql from the Markdown files in demo-docs/.
//   node scripts/generate-demo-seed.mjs
//
// Chunks and embeds each document with the same pipeline as the app, then writes SQL that
// inserts them as public_demo rows. Paste the SQL into the Supabase SQL Editor (which runs
// as the database owner, so no service-role key is needed on your machine).
// The SQL first deletes all existing public_demo rows, so re-running it is safe.
import { createHash, randomUUID } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { AutoTokenizer, pipeline } from "@huggingface/transformers";
import { chunkText, embeddingText } from "../src/lib/chunker.ts";
import { EMBEDDING_DIM, EMBEDDING_MODEL_LABEL, MODEL_DTYPE, MODEL_ID, MODEL_REVISION } from "../src/lib/embeddingConfig.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = join(root, "demo-docs");
const outFile = join(root, "supabase", "seed", "demo_seed.sql");

const q = (s) => `'${String(s).replaceAll("'", "''")}'`; // SQL string literal

const files = readdirSync(docsDir).filter((f) => f.endsWith(".md")).sort();
if (files.length === 0) throw new Error("No .md files in demo-docs/");

console.log("Loading model...");
const extractor = await pipeline("feature-extraction", MODEL_ID, { dtype: MODEL_DTYPE, revision: MODEL_REVISION });
const tokenizer = await AutoTokenizer.from_pretrained(MODEL_ID, { revision: MODEL_REVISION });
const count = (t) => tokenizer.encode(t, { add_special_tokens: false }).length;

const docRows = [];
const chunkRows = [];
for (const file of files) {
  const text = readFileSync(join(docsDir, file), "utf8");
  const docId = randomUUID();
  const chunks = chunkText(text, count);
  const vectors = [];
  for (let i = 0; i < chunks.length; i += 8) {
    const batch = chunks.slice(i, i + 8).map((c) => embeddingText(c));
    vectors.push(...(await extractor(batch, { pooling: "cls", normalize: true })).tolist());
  }
  if (vectors.some((v) => v.length !== EMBEDDING_DIM)) throw new Error("Unexpected embedding dimension");

  docRows.push(
    `(${q(docId)}, null, 'public_demo', 'upload', ${q(file)}, ${q(createHash("sha256").update(text).digest("hex"))}, 'ready')`,
  );
  chunks.forEach((c, i) => {
    const vec = `[${vectors[i].map((n) => Number(n.toFixed(6))).join(",")}]`;
    chunkRows.push(
      `(${q(docId)}, null, 'public_demo', ${c.index}, ${q(c.content)}, ${q(vec)}, ${q(EMBEDDING_MODEL_LABEL)}, ${c.locator === null ? "null" : q(c.locator)})`,
    );
  });
  console.log(`  ${file}: ${chunks.length} chunks`);
}

const sql = `-- GENERATED by scripts/generate-demo-seed.mjs from demo-docs/. Do not edit by hand.
-- Run in the Supabase SQL Editor (runs as the database owner, bypassing RLS).
-- Replaces ALL existing public_demo documents, so it is safe to re-run.
begin;

delete from public.rag_documents where visibility = 'public_demo';

insert into public.rag_documents (id, owner_id, visibility, source_type, title, content_hash, status) values
${docRows.join(",\n")};

insert into public.rag_chunks (document_id, owner_id, visibility, chunk_index, content, embedding, embedding_model, source_locator) values
${chunkRows.join(",\n")};

commit;
`;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, sql);
console.log(`Wrote ${outFile} (${(sql.length / 1024).toFixed(0)} KB, ${docRows.length} documents, ${chunkRows.length} chunks)`);
